#!/usr/bin/env python3

# acecalltablegen <Extension.cpp path> <Extension.hpp path> <output ACECallTable_Macro.cpp>

import sys
import re




def get_ace_call_arguments(arg_types):
    ret = ""

    for i in range(len(arg_types)):
        t = arg_types[i]
        ret += "*(" + arg_types[i] + " *)&Parameters[" + str(i) + "]"
        if i + 1 < len(arg_types):
            ret += " ,"

    return ret


def get_ace_call_arguments2(indent, arg_types):
    ret = ""

    for i in range(len(arg_types)):
        ret += indent
        ret += "    long arg" + str(i) + " = Parameters[" + str(i) + "];\n"

    return ret


def get_ace_call_arguments3(arg_types):
    ret = ""

    for i in range(len(arg_types)):
        ret += "*(" + arg_types[i] + " *)&arg" + str(i)

        if i + 1 < len(arg_types):
            ret += " ,"

    return ret




extcpp_path = ""
exthpp_path = ""
out_path = ""


for i in range(len(sys.argv)):
    arg = sys.argv[i]
    if i == 0:
        # first argument is the script name
        continue
    elif i == 1:
        extcpp_path = arg
        continue
    elif i == 2:
        exthpp_path = arg
        continue
    elif i == 3:
        out_path = arg
        continue

# ACE id, function name
linked_conditions = []
linked_actions = []
linked_expressions = []


# Look for LinkCondition, LinkAction, LinkExpression calls
link_condition_regex  = re.compile("LinkCondition\\( *([0-9]*) *, *([a-zA-Z0-9_]*) *\\);")
link_action_regex     = re.compile("LinkAction\\( *([0-9]*) *, *([a-zA-Z0-9_]*) *\\);")
link_expression_regex = re.compile("LinkExpression\\( *([0-9]*) *, *([a-zA-Z0-9_]*) *\\);")

with open(extcpp_path, "r") as extcpp:
    for line in extcpp.readlines():
        if m := link_condition_regex.search(line):
            linked_conditions += [{
                "id": m.group(1),
                "name": m.group(2),
            }]
        if m := link_action_regex.search(line):
            linked_actions += [{
                "id": m.group(1),
                "name": m.group(2),
            }]
        if m := link_expression_regex.search(line):
            linked_expressions += [{
                "id": m.group(1),
                "name": m.group(2),
            }]


# Look for funciton definitions of functions linked earlier

# list of dicts:
# key name
# string return_type
# string arg_types[]
function_definitions = {}

function_definition_regex = re.compile("([a-zA-Z0-9_]+) +([a-zA-Z0-9_]+)\\((.*)\\);")
single_argument_regex     = re.compile(" *(.+?)(?:,| *$)")
get_argument_type_regex   = re.compile("(.+?) +([a-zA-Z0-9_]+)$")

with open(exthpp_path, "r") as exthpp:
    for line in exthpp.readlines():
        if not (m := function_definition_regex.search(line)):
            continue

        function_name = m.group(2)
        function_definitions[function_name] = {
            "return_type": m.group(1),
            "arg_types": [],
        }

        arguments = m.group(3)

        while True:
            # get next argument from a list of arguments

            if not (m := single_argument_regex.search(arguments)):
                break

            argument = m.group(1)
            arguments = arguments[m.end():]

            # get argument type.
            if m := get_argument_type_regex.search(argument):
                function_definitions[function_name]["arg_types"] += [m.group(1)]


# Use the template to create the output

with open(out_path, "w") as out:
    out.write("// Generated by acecalltablegen.\n")
    out.write("#if DARKEDIF_ACE_CALL_TABLE_INDEX==0\n")

    indent = "    "

    # TODO: Verify that conditions work the same as expressions.

    for i in linked_conditions:
        function_id = i["id"]
        function_name = i["name"]
        function_def = function_definitions[function_name]

        if function_def is None:
            print("Couldn't find function definition for: \"{}()\"".format(function_name))
            continue

        out.write(indent + "case " + function_id + ":\n")
        out.write(indent + "    *((" + function_def["return_type"] + " *)&Result) = ext->" + function_name + "(")
        out.write(get_ace_call_arguments(function_def["arg_types"]) + ");\n")
        out.write(indent + "    break;\n")

    out.write("#elif DARKEDIF_ACE_CALL_TABLE_INDEX==1\n")

    for i in linked_actions:
        function_id = i["id"]
        function_name = i["name"]
        function_def = function_definitions[function_name]

        if function_def is None:
            print("Couldn't find function definition for: \"{}()\"".format(function_name))
            continue

        out.write(indent + "case " + function_id + ":\n")
        out.write(indent + "    return ext->" + function_name + "(")
        out.write(get_ace_call_arguments(function_def["arg_types"]) + "), 0;\n")


    out.write("#elif DARKEDIF_ACE_CALL_TABLE_INDEX==2\n")

    for i in linked_expressions:
        function_id = i["id"]
        function_name = i["name"]
        function_def = function_definitions[function_name]

        if function_def is None:
            print("Couldn't find function definition for: \"{}()\"".format(function_name))
            continue

        # FIXME: The compiler does something weird when building to wasm with optimizations (-O2, -O3)
        # instead of loading all parameters from memory it loads only the first one and the rest are set to 0.
        # but when the params are first saved in a variable and then later casted to the correct type it magicaly works.
        # old code works fine with msvc so this feels like a compiler bug.
        # tested with wasi-sdk 27.
        # TODO: recheck later with a more recent compiler. maybe find a minimal code to reproduce and submit an issue to llvm-project.
        # TODO: check if this bug happens for actions and conditions.
        out.write(indent + "case " + function_id + ": {\n")
        out.write(get_ace_call_arguments2(indent, function_def["arg_types"]) + "\n")
        out.write(indent + "    *((" + function_def["return_type"] + " *)&Result) = ext->" + function_name + "(")
        out.write(get_ace_call_arguments3(function_def["arg_types"]) + ");\n")
        out.write(indent + "    } break;\n")


    out.write("#else\n")
    out.write("#error Incorrect DarkEdif ACE Call Table index\n")
    out.write("#endif\n")
